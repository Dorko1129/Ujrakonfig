`timescale 1ns / 1ps

module prom_DMH (
    input  wire        sel,   // 0: "DMH" minta, 1: "INFO" minta
    input  wire [3:0]  addr,
    output wire [0:31] M
);

    reg [0:31] rom_dmh  [0:15];
    reg [0:31] rom_info [0:15];
    integer i;

    // Eredeti 16x32 minta ("DMH")
    parameter data_dmh = {
        32'b01111110000011000001101000000010,
        32'b01000001000011000001101000000010,
        32'b01000000100010100010101000000010,
        32'b01000000010010100010101000000010,
        32'b01000000001010100010101000000010,
        32'b01000000001010010100101000000010,
        32'b01000000001010010100101000000010,
        32'b01000000001010010100101111111110,
        32'b01000000001010001000101000000010,
        32'b01000000001010001000101000000010,
        32'b01000000001010001000101000000010,
        32'b01000000001010000000101000000010,
        32'b01000000010010000000101000000010,
        32'b01000000100010000000101000000010,
        32'b01000001000010000000101000000010,
        32'b01111110000010000000101000000010
    };

    // Új felirat ("INFO")
    parameter data_info = {
        32'b11111100110000101111111001111100,
        32'b00110000111000101100000011000011,
        32'b00110000111100101100000011000011,
        32'b00110000110110101111110011000011,
        32'b00110000110011101100000011000011,
        32'b00110000110001101100000011000011,
        32'b11111100110000101100000001111100,
        32'b00000000000000000000000000000000,
        32'b00000000000000000000000000000000,
        32'b00000000000000000000000000000000,
        32'b00000000000000000000000000000000,
        32'b00000000000000000000000000000000,
        32'b00000000000000000000000000000000,
        32'b00000000000000000000000000000000,
        32'b00000000000000000000000000000000,
        32'b00000000000000000000000000000000
    };

    initial begin
        for (i = 0; i < 16; i = i + 1) begin
            rom_dmh[i]  = data_dmh[(511 - 32 * i) -: 32];
            rom_info[i] = data_info[(511 - 32 * i) -: 32];
        end
    end

    assign M = (sel == 1'b1) ? rom_info[addr] : rom_dmh[addr];

endmodule
